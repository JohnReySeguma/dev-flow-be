/**
 * The frontend's demo tracker (lib/tracker/seed.ts), ported as data. Every time is an offset in
 * days from "now" (negative = past), so a fresh database always shows a sprint mid-flight.
 * Keep it in step with the frontend: same keys, workflows, sprints and states.
 */
import type { IssueType, Priority, StatusCategory } from "../generated/prisma/client.js";
import type { MemberRef } from "./accounts.js";

export type DemoStatus = { ref: string; name: string; category: StatusCategory };

export type DemoProject = {
  key: string;
  name: string;
  description: string;
  color: string;
  lead: MemberRef;
  workflow: DemoStatus[];
  nextIssueNumber: number;
  /** Days from now. */
  created: number;
};

export type DemoSprint =
  | {
      ref: string;
      project: string;
      number: number;
      goal: string;
      status: "completed";
      endDaysAgo: number;
      report: { committedPoints: number; completedPoints: number; completedIssues: number; carriedOverIssues: number };
    }
  | { ref: string; project: string; number: number; goal: string; status: "active"; start: number; end: number }
  | { ref: string; project: string; number: number; goal: string; status: "planned" };

export type DemoIssue = {
  key: string;
  sprint: string | null;
  status: string;
  type: IssueType;
  priority: Priority;
  title: string;
  assignee: MemberRef | null;
  tags: string[];
  git?: { kind: "pr"; number: number; state: "open" | "merged" | "draft" } | { kind: "commit"; sha: string };
  estimate: number | null;
  comments: number;
  /** Days from now. createdAt is five days earlier. */
  updated: number;
  due?: number;
  resolved?: number;
  description?: string;
};

